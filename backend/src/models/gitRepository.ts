import {
  DataTypes,
  Model,
  type CreationOptional,
  type InferAttributes,
  type InferCreationAttributes,
} from 'sequelize';
import { sequelize } from '../config/database';
import { encrypt, decrypt } from '../utils/encryption';

export type GitProvider = 'github' | 'gitlab' | 'gitea' | 'bitbucket';

const ENCRYPTED_FIELDS = ['access_token', 'ssh_key'] as const;

export class GitRepository extends Model<InferAttributes<GitRepository>, InferCreationAttributes<GitRepository>> {
  declare id: CreationOptional<string>;
  /** Friendly name for the repository */
  declare name: string;
  declare provider: GitProvider;
  /** Git repository URL (HTTPS) */
  declare repository_url: string;
  /** Branch to use for commits and sync */
  declare branch: CreationOptional<string>;
  /** Access token for authentication (encrypted at rest) */
  declare access_token: CreationOptional<string | null>;
  /** SSH private key, alternative to a token (encrypted at rest) */
  declare ssh_key: CreationOptional<string | null>;
  /** Whether this repository is active */
  declare enabled: CreationOptional<boolean>;
  /** Automatically commit configuration changes */
  declare auto_commit: CreationOptional<boolean>;
  /** GitOps mode: sync from Git as source of truth */
  declare auto_sync: CreationOptional<boolean>;
  /** Sync interval in seconds for GitOps mode */
  declare sync_interval: CreationOptional<number>;
  /** Last time config was synced from Git */
  declare last_sync: CreationOptional<Date | null>;
  /** SHA of last commit made or synced */
  declare last_commit_sha: CreationOptional<string | null>;
  /** Template for commit messages, supports {{changes}} placeholder */
  declare commit_message_template: CreationOptional<string>;
  declare createdAt: CreationOptional<Date>;
  declare updatedAt: CreationOptional<Date>;
}

GitRepository.init({
  id: {
    type: DataTypes.UUID,
    defaultValue: DataTypes.UUIDV4,
    primaryKey: true
  },
  name: {
    type: DataTypes.STRING,
    allowNull: false,
    comment: 'Friendly name for the repository'
  },
  provider: {
    type: DataTypes.ENUM('github', 'gitlab', 'gitea', 'bitbucket'),
    allowNull: false,
    comment: 'Git hosting provider'
  },
  repository_url: {
    type: DataTypes.STRING,
    allowNull: false,
    comment: 'Git repository URL (HTTPS)'
  },
  branch: {
    type: DataTypes.STRING,
    defaultValue: 'main',
    comment: 'Branch to use for commits and sync'
  },
  access_token: {
    type: DataTypes.TEXT,
    allowNull: true,
    comment: 'Encrypted access token for authentication'
  },
  ssh_key: {
    type: DataTypes.TEXT,
    allowNull: true,
    comment: 'Encrypted SSH private key (alternative to token)'
  },
  enabled: {
    type: DataTypes.BOOLEAN,
    defaultValue: true,
    comment: 'Whether this repository is active'
  },
  auto_commit: {
    type: DataTypes.BOOLEAN,
    defaultValue: true,
    comment: 'Automatically commit configuration changes'
  },
  auto_sync: {
    type: DataTypes.BOOLEAN,
    defaultValue: false,
    comment: 'GitOps mode: sync from Git as source of truth'
  },
  sync_interval: {
    type: DataTypes.INTEGER,
    defaultValue: 300,
    comment: 'Sync interval in seconds for GitOps mode'
  },
  last_sync: {
    type: DataTypes.DATE,
    allowNull: true,
    comment: 'Last time config was synced from Git'
  },
  last_commit_sha: {
    type: DataTypes.STRING,
    allowNull: true,
    comment: 'SHA of last commit made or synced'
  },
  commit_message_template: {
    type: DataTypes.TEXT,
    defaultValue: 'chore: update CaddyManager configuration\n\n{{changes}}\n\n🤖 Generated by CaddyManager',
    comment: 'Template for commit messages, supports {{changes}} placeholder'
  },
  createdAt: DataTypes.DATE,
  updatedAt: DataTypes.DATE
}, {
  sequelize,
  modelName: 'GitRepository',
  tableName: 'git_repositories',
  timestamps: true,
  hooks: {
    // ── Encrypt sensitive fields before persisting ──────────────────────────────
    beforeCreate: (instance) => {
      for (const field of ENCRYPTED_FIELDS) {
        const value = instance[field];
        if (value) {
          instance[field] = encrypt(value);
        }
      }
    },
    beforeUpdate: (instance) => {
      for (const field of ENCRYPTED_FIELDS) {
        const value = instance[field];
        if (instance.changed(field) && value) {
          instance[field] = encrypt(value);
        }
      }
    },
    // ── Decrypt sensitive fields after reading ──────────────────────────────────
    afterFind: (result) => {
      if (!result) return;
      const items = Array.isArray(result) ? result : [result];
      for (const repo of items) {
        if (!repo) continue;
        for (const field of ENCRYPTED_FIELDS) {
          const value = repo[field];
          if (value) {
            repo[field] = decrypt(value);
          }
        }
      }
    }
  }
});
